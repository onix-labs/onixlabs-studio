import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import * as path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  findVirtualEnvironment,
  readPipfileLock,
  readTomlLock,
  readVirtualEnvironment,
} from './installed';

describe('readTomlLock', () => {
  it('readTomlLock_aUvLock_readsEachPackageByNormalisedName', () => {
    // Arrange
    const text: string = [
      'version = 1',
      'requires-python = ">=3.11"',
      '',
      '[[package]]',
      'name = "Requests"',
      'version = "2.31.0"',
      'source = { registry = "https://pypi.org/simple" }',
      'dependencies = [',
      '    { name = "certifi" },',
      ']',
      'wheels = [',
      '    { url = "https://files.pythonhosted.org/requests.whl", hash = "sha256:abc", size = 1 },',
      ']',
      '',
      '[package.optional-dependencies]',
      'socks = [{ name = "pysocks" }]',
      '',
      '[[package]]',
      'name = "typing_extensions"',
      'version = "4.12.2"',
      'source = { registry = "https://pypi.org/simple" }',
    ].join('\n');

    // Act
    const versions: ReadonlyMap<string, string> = readTomlLock(text);

    // Assert
    expect([...versions]).toEqual([
      ['requests', '2.31.0'],
      ['typing-extensions', '4.12.2'],
    ]);
  });

  it('readTomlLock_aPoetryLock_readsEachPackage', () => {
    // Arrange
    const text: string = [
      '# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.',
      '',
      '[[package]]',
      'name = "certifi"',
      'version = "2024.7.4"',
      'description = "Python package for providing Mozilla\'s CA Bundle."',
      'optional = false',
      'python-versions = ">=3.6"',
      'files = [',
      '    {file = "certifi-2024.7.4-py3-none-any.whl", hash = "sha256:c19"},',
      ']',
      '',
      '[metadata]',
      'lock-version = "2.0"',
      'python-versions = "^3.11"',
      'content-hash = "abc"',
    ].join('\n');

    // Act
    const versions: ReadonlyMap<string, string> = readTomlLock(text);

    // Assert
    expect([...versions]).toEqual([['certifi', '2024.7.4']]);
  });

  it('readTomlLock_notToml_readsNothing', () => {
    // Act
    const versions: ReadonlyMap<string, string> = readTomlLock('[[package]\nname = ');

    // Assert
    expect(versions.size).toBe(0);
  });
});

describe('readPipfileLock', () => {
  it('readPipfileLock_defaultAndDevelop_readsPinnedVersions', () => {
    // Arrange
    const text: string = JSON.stringify({
      _meta: { hash: { sha256: 'x' } },
      default: {
        requests: { version: '==2.31.0', hashes: [] },
        mine: { git: 'https://x', ref: 'abc' },
      },
      develop: { PyTest: { version: '==8.2.0' } },
    });

    // Act
    const versions: ReadonlyMap<string, string> = readPipfileLock(text);

    // Assert
    expect([...versions]).toEqual([
      ['requests', '2.31.0'],
      ['pytest', '8.2.0'],
    ]);
  });

  it('readPipfileLock_notJson_readsNothing', () => {
    // Act
    const versions: ReadonlyMap<string, string> = readPipfileLock('{');

    // Assert
    expect(versions.size).toBe(0);
  });
});

describe('virtual environments', () => {
  let root: string = '';

  beforeEach(() => {
    root = realpathSync(mkdtempSync(path.join(tmpdir(), 'studio-pypi-venv-')));
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
  });

  it('readVirtualEnvironment_distInfoFolders_areTheInstalledVersions', async () => {
    // Arrange
    const sitePackages: string = path.join(root, '.venv', 'lib', 'python3.12', 'site-packages');
    mkdirSync(path.join(sitePackages, 'requests-2.31.0.dist-info'), { recursive: true });
    mkdirSync(path.join(sitePackages, 'typing_extensions-4.12.2.dist-info'));
    mkdirSync(path.join(sitePackages, 'requests'));
    writeFileSync(path.join(sitePackages, 'fake-1.0.dist-info'), '');

    // Act
    const versions: ReadonlyMap<string, string> = await readVirtualEnvironment(
      path.join(root, '.venv'),
    );

    // Assert
    expect(new Map<string, string>(versions)).toEqual(
      new Map<string, string>([
        ['requests', '2.31.0'],
        ['typing-extensions', '4.12.2'],
      ]),
    );
  });

  it('findVirtualEnvironment_aFolderWithPyvenvCfg_isFound_andOneWithoutIsNot', async () => {
    // Arrange
    mkdirSync(path.join(root, 'venv'));
    writeFileSync(path.join(root, 'venv', 'pyvenv.cfg'), 'home = /usr/bin\n');
    mkdirSync(path.join(root, '.venv'));

    // Act
    const venv: string | null = await findVirtualEnvironment(root);

    // Assert
    expect(venv).toBe(path.join(root, 'venv'));
  });
});
